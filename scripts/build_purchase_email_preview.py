"""Bundle editable purchase email sources for the local, offline review gallery."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / "marketing/templates/purchase-flow"


def main():
    data = json.loads((DIRECTORY / "flow.json").read_text(encoding="utf-8"))
    for message in data["messages"]:
        message["html"] = (ROOT / "backend/app/email_templates/purchase" / f"{message['id']}.html").read_text(encoding="utf-8")
        message["text"] = (ROOT / "backend/app/email_templates/purchase" / f"{message['id']}.txt").read_text(encoding="utf-8")
    bundle = json.dumps(data, ensure_ascii=False, indent=2)
    (DIRECTORY / "preview-data.js").write_text(
        "// Generated by scripts/build_purchase_email_preview.py; edit HTML/TXT/flow.json sources.\n"
        f"window.PURCHASE_EMAIL_PREVIEW = {bundle};\n", encoding="utf-8", newline="\n",
    )
    print(f"Bundled {len(data['messages'])} purchase email previews; no messages sent.")


if __name__ == "__main__":
    main()
